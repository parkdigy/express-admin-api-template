/********************************************************************************************************************
 * Multer 파일 업로드 처리 미들웨어
 * - 다중 파일 업로드 처리
 * ******************************************************************************************************************/
import multer from 'multer';

export default function (maxCount: number, name = 'files', dest = '@uploads/') {
  return multer({ dest }).array(name, maxCount);
}
